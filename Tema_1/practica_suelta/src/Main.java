void main(String[] args) {

    Scanner sc = new Scanner(System.in);

    System.out.println("Dime dos numeros");

    System.out.print("> ");

    int n1 = sc.nextInt();

    System.out.print("> ");

    int n2 = sc.nextInt();

    System.out.println("La suma seria " + (n1 + n2));

    System.out.println("La resta seria " + (n1 - n2));

    System.out.println("La multiplicacion seria " + (n1 * n2));

    System.out.println("La division seria " + (n1 / n2));

}
